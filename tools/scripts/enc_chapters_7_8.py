"""Encyclopedia chapters 7–8: Analogs/interchangeability, Manufacturers/brands."""

import csv
import os
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[2]


def _load_brands(n: int = 60) -> tuple[list[str], list[list[str]]]:
    """Load brand data from brands.csv for chapter 8 table."""
    csv_path = _REPO_ROOT / "data" / "brands.csv"
    headers = ["Бренд", "Описание (краткое)"]
    rows: list[list[str]] = []
    if not csv_path.exists():
        return headers, rows
    try:
        with open(csv_path, encoding="utf-8") as f:
            reader = csv.DictReader(f)
            for row in reader:
                name = str(row.get("Name", "") or "").strip()
                desc = str(row.get("Description", "") or "").strip()
                if not name:
                    continue
                # Truncate description to first sentence or 80 chars
                short_desc = desc.split(".")[0][:80] if desc else "—"
                rows.append([name[:30], short_desc])
                if len(rows) >= n:
                    break
    except Exception:
        pass
    return headers, rows


def _load_analogs_sample() -> tuple[list[str], list[list[str]]]:
    """Load a cross-reference analog sample from nomenclature.csv."""
    csv_path = _REPO_ROOT / "data" / "nomenclature.csv"
    headers = ["Оригинал (бренд)", "Артикул оригинала", "Аналог"]
    rows: list[list[str]] = []
    if not csv_path.exists():
        return headers, rows
    try:
        with open(csv_path, encoding="utf-8") as f:
            reader = csv.DictReader(f)
            for row in reader:
                brand = str(row.get("Brand", "") or "").strip()
                art = str(row.get("Product Name", "") or "").strip()
                analog = str(row.get("Analog Name", "") or "").strip()
                if not art or not analog:
                    continue
                rows.append([brand[:20], art[:25], analog[:25]])
                if len(rows) >= 40:
                    break
    except Exception:
        pass
    return headers, rows


_brands_headers, _brands_rows = _load_brands(60)
_analogs_headers, _analogs_rows = _load_analogs_sample()

